"""Every result table of the benchmark, from the files saved in this repository.
Nothing is sent to a model.

    python3 scripts/results.py            # print
    python3 scripts/results.py --write    # also write docs/RESULTS.md
"""

import json
import statistics
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "scripts"))
from agreement import report  # noqa: E402
from build_dashboard_data import HARNESS, MODELS, PAPERS, frac, matches  # noqa: E402
from score_coverage import score  # noqa: E402


def run_totals(run: str) -> dict:
    fid = json.loads((ROOT / "runs" / run / "scores.json").read_text())
    t = dict(points=0.0, strict=0.0, answers=0.0, core=0.0, core_total=0.0, serious=0, mild=0, quotes=0, verbatim=0, located=0,
             claims=0, catches=0.0, catches_total=0.0, primary=0.0)
    for pid, _ in PAPERS:
        s = score(json.loads((ROOT / "gold" / f"pone.{pid}.json").read_text()), matches(run, pid))
        q = fid["pone." + pid]
        for k, v in dict(points=frac(s["acceptable answers, points"])[0], answers=frac(s["acceptable answers, points"])[1],
                         strict=frac(s["  strict (an answer split across entries earns half)"])[0],
                         core=frac(s["core findings"])[0], core_total=frac(s["core findings"])[1],
                         serious=int(s["serious flags"]), mild=int(s["mild flags"]), quotes=q["quotes"], verbatim=q["faithful"],
                         located=q["located"], claims=q["entries"], catches=frac(s["critical catches (bonus)"])[0],
                         catches_total=frac(s["critical catches (bonus)"])[1], primary=frac(s["primary framework named"])[0]).items():
            t[k] += v
    t["coverage"] = 100 * t["points"] / t["answers"]
    return t


def table(header: list[str], rows: list[list]) -> str:
    out = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def main() -> str:
    lines = ["# Results", "", "Generated by `python3 scripts/results.py --write` from the saved replies, matches and labels.",
             "Coverage is points over the 187 accepted answers of the five papers. One judge (Claude Opus 5.5 agents) matched every note.", ""]
    rows = []
    for _, name, runs in MODELS:
        ts = [run_totals(r) for r in runs]
        cov = [t["coverage"] for t in ts]
        mean = statistics.mean
        rows.append((mean(cov), [name, len(ts), f"{mean(cov):.0f}%", " / ".join(f"{c:.0f}" for c in cov),
                                 f"{mean(t['core'] for t in ts):.1f}/{ts[0]['core_total']:g}",
                                 f"{sum(t['verbatim'] for t in ts)}/{sum(t['quotes'] for t in ts)}",
                                 f"{sum(t['located'] for t in ts)}/{sum(t['quotes'] for t in ts)}",
                                 " / ".join(str(t["serious"]) for t in ts), " / ".join(str(t["mild"]) for t in ts),
                                 f"{mean(t['strict'] for t in ts) / ts[0]['answers']:.0%}",
                                 f"{max(t['catches'] for t in ts):g}/{ts[0]['catches_total']:g}"]))
    lines += ["## Models on their own", "",
              table(["Model", "Runs", "Coverage, mean", "Coverage by run", "Core findings, mean", "Quotes word for word", "Page correct",
                     "Serious flags by run", "Mild flags by run", "Coverage, strict rule", "Critical reading bonus"],
                    [r for _, r in sorted(rows, key=lambda x: -x[0])]), "",
              "Qwen3 4B's three runs are sampled (temperature 0.7, top-p 0.8, top-k 20, seeds 1 to 3). Its harness rows start from an earlier run at temperature 0. "
              "The six other local setups were run by [Ellian-Eorwyn](https://github.com/Ellian-Eorwyn) on one RTX 3090 on 2026-11-25, each with its own sampling (docs/local-runs-2026-11-25/). "
              "The strict rule gives half credit to an answer split across entries.", ""]
    rows = []
    for name, setting, run in HARNESS:
        t = run_totals(run)
        rows.append([name, setting, f"{t['coverage']:.0f}%", f"{t['core']:g}/{t['core_total']:g}", t["serious"], t["mild"], t["claims"],
                     f"{t['verbatim']}/{t['quotes']}"])
    lines += ["## With the harness", "",
              table(["Model", "Setting", "Coverage", "Core findings", "Serious flags", "Mild flags", "Claims", "Quotes word for word"], rows), "",
              "Each harness row starts from the model's first run. The contributed local setups ran the harness with their own output allowances (docs/REPRODUCE.md).", ""]
    a = report(str(ROOT / "labeling" / "sample1"))
    lines += ["## The judge against the human labeler", "",
              f"Sample 1: {a['items']} accepted answers, weighted toward hard cases, labeled blind by the human labeler.", "",
              table(["Matching", "Same label as the human", "Cohen's kappa", "Stricter than the human", "More generous"],
                    [[n, a[n]["same label"], a[n]["Cohen's kappa"], a[n]["judge stricter than human"], a[n]["judge more generous than human"]]
                     for n in ("Claude Opus 5.5 agents", "the assistant's hand matching")]), ""]
    d = a["where the two matchings disagreed"]
    lines += [f"On the {d['items']} items where the two matchings disagreed, the human sided with the agents {d['human sided with the agents']} times "
              f"and with the hand matching {d['human sided with the hand matching']} times.", ""]
    return "\n".join(lines)


if __name__ == "__main__":
    text = main()
    print(text)
    if "--write" in sys.argv:
        (ROOT / "docs" / "RESULTS.md").write_text(text + "\n")
